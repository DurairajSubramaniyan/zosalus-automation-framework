/**
 * Generate a complete, unique, species-specific Pet + Health Records + Condition + Episode bundle
 * for a given slot index (0..8 covering 9 distinct species).
 *
 * @param {number} index
 */
function generateSpeciesCompleteBundle(index) {
  const template =
    SPECIES_CLINICAL_PROFILES[index % SPECIES_CLINICAL_PROFILES.length];
  const sfx = shortTag();
  const petName = `${pick(template.names)}${randomInt(10, 99)}`;
  const breed = pick(template.breeds);
  const month = String(randomInt(1, 11)).padStart(2, '0');
  const day = String(randomInt(1, 25)).padStart(2, '0');
  const year = randomInt(2021, 2024);

  return {
    pet: {
      name: petName,
      species: template.species,
      breed,
      birthdate: `${month}/${day}/${year}`,
      sex: pick(['Male', 'Female']),
      neuterStatus: 'Neutered / Spayed',
      colorMarkings: pick(template.colors),
      microchipNumber: generateIsoMicrochip15(),
    },
    vaccination: {
      vaccineName: `${template.vaccine.name} #${sfx}`,
      dateAdministered: generatePastDateMmDdYyyy(2025),
      nextDueDate: generatePastDateMmDdYyyy(2027),
      route: template.vaccine.route,
      manufacturer: template.vaccine.manufacturer,
      lotNumber: `LOT-${sfx}`,
      costAmount: `${randomInt(45, 120)}.00`,
      notes: `${template.species} (${breed}) immunization for ${petName} [${sfx}].`,
    },
    medication: {
      drugName: `${template.medication.drugName} ${sfx}`,
      brandName: `${template.medication.brandName}`,
      strength: template.medication.strength,
      formulation: template.medication.formulation,
      doseAmount: template.medication.doseAmount,
      doseUnit: template.medication.doseUnit,
      frequency: template.medication.frequency,
      route: template.medication.route,
      startDate: '05/05/2025',
      endDate: '05/20/2025',
      rxNumber: `RX-${sfx}`,
      pharmacyName: template.medication.pharmacy,
      refillsRemaining: String(randomInt(1, 3)),
      costAmount: `${randomInt(35, 110)}.00`,
      notes: `Species-specific ${template.species} prescription for ${petName} (${sfx}).`,
    },
    labResult: {
      testName: `${template.lab.testName} [${sfx}]`,
      testPanel: template.lab.panel,
      value: template.lab.value,
      unit: template.lab.unit,
      referenceLow: template.lab.refLow,
      referenceHigh: template.lab.refHigh,
      testDate: generatePastDateMmDdYyyy(2025),
      labName: template.lab.labName,
      notes: `Normal ${template.species} diagnostic interval for ${petName} (${sfx}).`,
      costAmount: `${randomInt(75, 195)}.00`,
    },
    vitalSigns: {
      ...template.vitals,
      mucousMembraneColour: 'Pink',
      recordedAt: generatePastDateMmDdYyyy(2025),
      notes: `${template.species} SOAP wellness exam for ${petName} (${breed}) [${sfx}].`,
    },
    allergy: {
      allergen: `${template.allergy.allergen} (${sfx})`,
      allergenType: template.allergy.allergenType,
      severity: template.allergy.severity,
      reaction: `${template.allergy.reaction} [${petName} ${sfx}]`,
      confirmedDate: generatePastDateMmDdYyyy(2025),
      notes: `${template.species} contraindication documented for ${petName} (${sfx}).`,
    },
    condition: {
      conditionName: `${template.condition.conditionName} ${sfx}`,
      status: template.condition.status,
      severity: template.condition.severity,
      firstDiagnosedDate: generatePastDateMmDdYyyy(2025),
      isInsuranceRelevant: true,
      icdCode: template.condition.icdCode,
      notes: `${template.condition.notes} [Pet: ${petName} - ${template.species}]`,
    },
    episode: {
      linkedConditionName: `${template.condition.conditionName} ${sfx}`,
      customSymptomFallback: `${template.species} Acute Symptom ${sfx}`,
      episodeDate: generatePastDateMmDdYyyy(2025),
      severity: 'Moderate',
      durationHours: '1',
      description: `${template.episode.description} [${petName} ${sfx}]`,
      triggers: `${template.episode.triggers} (${sfx})`,
      extraNotes: `Owner follow-up note for ${petName} (${template.species}) [${sfx}].`,
      wasMedicationGiven: true,
      medicationGiven: `${template.episode.medicationGiven} ${sfx}`,
      medicationRoute: 'Oral',
      responseToMedication: 'Improved',
    },
  };
}

